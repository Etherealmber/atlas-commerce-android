/** Builds a stable, non-composable ImageVector so navigation metadata can keep static icon references. */
private fun atlasLucideVector(definition: LucideIconDefinition, autoMirror: Boolean = false): ImageVector =
    ImageVector.Builder(
        name = definition.name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
        autoMirror = autoMirror,
    ).apply { definition.paths(this, 2f) }.build()
